"""a9: width x depth grid of the dense all-core detector, to find configurations near the 10.82 ms budget (YOLOv8n ReLU, INT8, 3 cores, a4 method).

    .venv/bin/python -m ai.research.all_core.grid.scale_grid list
    .venv/bin/python -m ai.research.all_core.grid.scale_grid audit [--rknn-dir DIR] [--precision int8]
list   writes the yamls and prints parameters and GFLOPs of every grid point (no compile, no board).
audit  compiles each grid graph on the PC like a7 (A/B check, blockers) and, with --rknn-dir, writes the .rknn files for the board.
Width scales every channel of allcore_dense.yaml (32/32/64/128/256 backbone, 64/128/128/256 neck) by w and rounds. Depth is the repeat count
of the Conv3x3 row of each backbone stage (2 in allcore_dense.yaml). The neck stays one conv per row. w = 1.0, d = 2 must equal allcore_dense.
Writes experiments/research/all_core/a9_scale_grid/{yamls/,compile_results.json,compile_report.md}. The board results.json and report.md of the same folder come from board_measure analyze --exp a9_scale_grid.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch
from ultralytics import YOLO

import ai.research.all_core.ultra  # noqa: F401  registers AllCoreDetect before any yaml is parsed
from ai.research.all_core.audit.compile_audit import RESEARCH_DIR
from ai.research.all_core.candidates.nets import complexity
from ai.research.all_core.audit.op_class import measured
from ai.research.all_core.audit.trainable_audit import Raw, audit

OUT = RESEARCH_DIR / "a9_scale_grid"
GRID = [(1.0, 2), (1.5, 2), (1.5, 3), (1.5, 4), (2.0, 2), (2.0, 3), (2.0, 4), (2.5, 2), (2.5, 3),
        (1.25, 3), (1.25, 4), (1.5, 1), (1.75, 1), (1.0, 6), (1.0, 10)]  # (width multiplier, depth); (1.0, 2) is the a7 control. (1.25, 3) to (1.0, 6): a9c, points near the raw-head ReLU budget (6.77 ms). (1.0, 10): a9d, depth is cheap at nano width
DENSE_PARAMS = 3_379_771  # allcore_dense, a7_trainable_audit/report.md


def name(w: float, d: int) -> str:
    return f"dense_w{round(w * 100)}_d{d}"


def yaml_text(w: float, d: int) -> str:
    c = lambda x: round(x * w)  # noqa: E731
    return f"""# a9 grid point: width x{w}, depth {d}. Generated by ai/research/all_core/grid/scale_grid.py from the layout of ai/models/allcore_dense/allcore_dense.yaml.
nc: 5
reg_max: 1
activation: nn.ReLU()

backbone:
  - [-1, 1, Conv, [{c(32)}, 3, 2]] # 0 stem /2
  - [-1, 1, Conv, [{c(32)}, 3, 2]] # 1 /4
  - [-1, {d}, Conv, [{c(32)}, 3, 1]] # 2 block s4
  - [-1, 1, Conv, [{c(64)}, 3, 2]] # 3 /8
  - [-1, {d}, Conv, [{c(64)}, 3, 1]] # 4 P3
  - [-1, 1, Conv, [{c(128)}, 3, 2]] # 5 /16
  - [-1, {d}, Conv, [{c(128)}, 3, 1]] # 6 P4
  - [-1, 1, Conv, [{c(256)}, 3, 2]] # 7 /32
  - [-1, {d}, Conv, [{c(256)}, 3, 1]] # 8 P5

head:
  - [4, 1, Conv, [{c(64)}, 3, 2]] # 9 down P3 to /16
  - [[-1, 6], 1, Concat, [1]] # 10 cat P4
  - [-1, 1, Conv, [{c(128)}, 3, 1]] # 11 n4
  - [-1, 1, Conv, [{c(128)}, 3, 2]] # 12 down n4 to /32
  - [[-1, 8], 1, Concat, [1]] # 13 cat P5
  - [-1, 1, Conv, [{c(256)}, 3, 1]] # 14 n5
  - [[4, 11, 14], 1, Detect, [nc]] # 15 Detect(n3 = P3, n4, n5)
"""


def write_yamls() -> dict[str, Path]:
    (OUT / "yamls").mkdir(parents=True, exist_ok=True)
    paths = {}
    for w, d in GRID:
        p = OUT / "yamls" / f"{name(w, d)}.yaml"
        p.write_text(yaml_text(w, d))
        paths[name(w, d)] = p
    return paths


def cmd_list() -> None:
    x = torch.randn(1, 3, 640, 640)
    rows = []
    for n, p in write_yamls().items():
        cx = complexity(Raw(YOLO(str(p)).model.eval()).eval(), x)
        rows.append((n, cx["params"], cx["gflops"]))
        print(f"{n:16s} params={cx['params']:>10,} gflops={cx['gflops']}")
    assert rows[0][1] == DENSE_PARAMS, f"control {rows[0][0]} has {rows[0][1]} params, a7 allcore_dense has {DENSE_PARAMS}"


def cmd_audit(precisions: list[str], rknn_dir: Path | None, only: list[str] | None) -> None:
    table, res = measured(), []
    for n, p in write_yamls().items():
        if only and n not in only:
            continue
        for prec in precisions:
            r = audit(n, prec, table, rknn_dir, weights=str(p))
            res.append(r)
            print(f"{n:16s} {prec:5s} layers={r['layers']} params={r['params']} gflops={r['gflops']} cycles={r['total_cycles']} blockers={r['blockers']}", flush=True)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / ("compile_results_only.json" if only else "compile_results.json")).write_text(json.dumps(res, indent=1) + "\n")
    lines = ["# a9: width x depth grid of the dense all-core detector (PC compile, 640x640, nc=5)", "",
             "| model | prec | layers | params | GFLOPs | cycles M | blockers |", "|---|---|---|---|---|---|---|"]
    for r in res:
        lines.append(f"| {r['model']} | {r['precision']} | {r['layers']} | {r['params']} | {r['gflops']} | {r['total_cycles'] / 1e6:.1f} | {r['blockers'] or '-'} |")
    (OUT / ("compile_report_only.md" if only else "compile_report.md")).write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=("list", "audit"))
    ap.add_argument("--precision", default="int8")
    ap.add_argument("--rknn-dir", type=Path)
    ap.add_argument("--only", help="audit: comma separated grid names, e.g. dense_w125_d3. Writes compile_*_only.* so the full-grid files stay")
    a = ap.parse_args()
    cmd_list() if a.cmd == "list" else cmd_audit(a.precision.split(","), a.rknn_dir, a.only.split(",") if a.only else None)


if __name__ == "__main__":
    main()
